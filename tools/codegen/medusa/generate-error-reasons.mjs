#!/usr/bin/env node
/**
 * T-214: the one-sentence reason a dry-run report gives for each refusal and notice code, generated from the
 * doc comment on the code — the same comments the published error reference is generated from — into
 * packages/einvoice-medusa/src/generated/error-reasons.ts. Never from an error's message, which can name
 * amounts (D-08).
 *
 * The reason is the comment's first sentence, after a leading "Issued." or "Not issued:" (the report's outcome
 * class says that already). A code without a comment, or a reason that points into the private planning log,
 * stops the script: the report would show a bare code or an internal reference otherwise.
 *
 * Reads the TypeScript sources with the compiler API — no build needed. Deterministic: same comments in, same
 * file out (codes sorted).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../../..");
const OUT_FILE = resolve(REPO_ROOT, "packages/einvoice-medusa/src/generated/error-reasons.ts");

/** Every code a plan's refusal or notice can carry: the core's, the plugin's own, the check against Medusa. */
const SOURCES = [
  "packages/einvoice-commerce/src/error-codes.ts",
  "packages/einvoice-medusa/src/errors.ts",
  "packages/einvoice-medusa/src/mapping/charged-reconciliation.ts",
];
const TYPES = new Set([
  "TaxRuleCode",
  "CommerceErrorCode",
  "PluginErrorCode",
  "InvoiceNoticeCode",
  "InvoiceBlockCode",
]);

/** The text of the `/** … *\/` comment between `from` and the member — before its `|` — without the markers. */
function docComment(text, from, to) {
  const between = text.slice(from, to);
  const comments = [...between.matchAll(/\/\*\*([\s\S]*?)\*\//g)];
  const last = comments.at(-1);
  if (last === undefined || !/^[\s|]*$/.test(between.slice(last.index + last[0].length)))
    return undefined;
  return last[1]
    .split("\n")
    .map((line) => line.replace(/^\s*\*\s?/, ""))
    .join(" ")
    .replace(/\s+/g, " ")
    .trim();
}

/** The first sentence: up to a full stop followed by a capital letter, a backtick or the end. */
function firstSentence(comment) {
  const body = comment.replace(/^Issued\.\s+/, "").replace(/^Not issued:\s+/, "");
  const capitalised = body.charAt(0).toUpperCase() + body.slice(1);
  const end = /\.(?=\s+[A-Z`]|$)/.exec(capitalised);
  return end === null ? capitalised : capitalised.slice(0, end.index + 1);
}

function reasonsOf(path) {
  const text = readFileSync(resolve(REPO_ROOT, path), "utf8");
  const source = ts.createSourceFile(path, text, ts.ScriptTarget.ES2022, true);
  const found = [];
  for (const statement of source.statements) {
    if (!ts.isTypeAliasDeclaration(statement) || !TYPES.has(statement.name.text)) continue;
    const members = ts.isUnionTypeNode(statement.type) ? statement.type.types : [statement.type];
    members.forEach((member, index) => {
      if (!ts.isLiteralTypeNode(member) || !ts.isStringLiteral(member.literal)) return;
      const from =
        index === 0 ? statement.name.end : (members[index - 1]?.end ?? statement.name.end);
      const comment = docComment(text, from, member.getStart(source));
      found.push({ code: member.literal.text, comment, path });
    });
  }
  return found;
}

const reasons = new Map();
for (const { code, comment, path } of SOURCES.flatMap(reasonsOf)) {
  // A code declared twice (the plugin repeats the core's `UNSUPPORTED_SELLER_COUNTRY`) keeps the comment it has.
  if (comment === undefined) {
    if (!reasons.has(code)) reasons.set(code, { path, reason: undefined });
    continue;
  }
  if (reasons.get(code)?.reason === undefined)
    reasons.set(code, { path, reason: firstSentence(comment) });
}

const problems = [...reasons.entries()].flatMap(([code, { path, reason }]) =>
  reason === undefined
    ? [`${code} (${path}) has no doc comment`]
    : /\b[TPMD]-\d{2,3}\b/.test(reason)
      ? [`${code} (${path}): its reason names an internal reference — "${reason}"`]
      : [],
);
if (problems.length > 0) {
  console.error(problems.join("\n"));
  process.exit(1);
}

const entries = [...reasons.entries()]
  .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
  .map(([code, { reason }]) => `  ${code}: ${JSON.stringify(reason)},`);

const output = `/**
 * Generated by tools/codegen/medusa/generate-error-reasons.mjs — do not edit; run \`pnpm codegen:error-reasons\`.
 * Source: the doc comments on the codes in ${SOURCES.join(", ")}.
 * The first sentence of each, after a leading "Issued." or "Not issued:".
 */
export const ERROR_REASONS: Readonly<Record<string, string>> = {
${entries.join("\n")}
};
`;
writeFileSync(OUT_FILE, output);
console.error(`wrote ${OUT_FILE} (${entries.length} codes)`);
